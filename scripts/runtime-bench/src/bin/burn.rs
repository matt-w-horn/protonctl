//! burn: Rust generated from the dynamo export at build time, on the CPU
//! (`burn flex`) or on Metal (`burn metal`).
extern crate alloc;

use burn::prelude::*;

#[expect(
    dead_code,
    reason = "generated by burn-onnx: from_bytes is unused here"
)]
mod model {
    include!(concat!(env!("OUT_DIR"), "/model/otter-dynamo.rs"));
}

fn bench<B: Backend>(label: &str, device: B::Device) -> anyhow::Result<()> {
    let m =
        model::Model::<B>::from_file(concat!(env!("OUT_DIR"), "/model/otter-dynamo.bpk"), &device);
    for name in runtime_bench::CASES {
        let c = runtime_bench::case(name)?;
        let n = c.tokens;
        let ints2 = |v: &Vec<i64>| {
            Tensor::<B, 2, Int>::from_data(TensorData::new(v.clone(), [1, n]), &device)
        };
        let ints1 = |v: &Vec<i64>| {
            Tensor::<B, 1, Int>::from_data(TensorData::new(v.clone(), [v.len()]), &device)
        };
        let got = runtime_bench::time(&format!("burn/{label}"), name, || {
            m.forward(
                ints2(&c.input_ids),
                ints2(&c.attention_mask),
                ints1(&c.span_start),
                ints1(&c.span_end),
                ints1(&c.span_len),
                ints1(&c.label_pos),
            )
            .into_data()
            .to_vec::<f32>()
            .expect("f32 logits")
        });
        runtime_bench::check(&format!("burn/{label}"), name, &c, &got);
    }
    Ok(())
}

fn main() -> anyhow::Result<()> {
    match std::env::args().nth(1).as_deref() {
        Some("metal") => bench::<burn::backend::Metal>("metal", Default::default()),
        _ => bench::<burn::backend::Flex>("flex", Default::default()),
    }
}
